source("r/slp_protocol.R")
source("r/slp_native.R")
source("r/semantic_reference.R")
x <- matrix(c(1, 2, 3, 4, 5, 6), nrow=2, byrow=TRUE)
frame <- slp_encode(x, request_id=99)
stopifnot(length(frame) == 80L)
stopifnot(identical(rawToChar(frame[1:4]), "SLP1"))
stopifnot(identical(as.integer(frame[5:8]), c(1L, 1L, 1L, 0L)))
# Decode row-major payload in R for cross-language layout parity.
payload <- readBin(frame[33:length(frame)], what="double", n=6, size=8L, endian="little")
stopifnot(identical(payload, c(1, 2, 3, 4, 5, 6)))
stopifnot(identical(matrix(payload, nrow=2, byrow=TRUE), x))
lib <- Sys.getenv("SLP_ZIG_LIBRARY", "")
if (!nzchar(lib) || !file.exists(lib)) stop("SLP_ZIG_LIBRARY must point to the compiled Zig library")
sl_load(lib)
p <- sl_softmax_zig_safe(x)
expected <- sl_softmax(x)
stopifnot(isTRUE(all.equal(p, expected, tolerance=1e-12)))
stopifnot(isTRUE(all.equal(sl_entropy_zig_safe(p), sl_entropy(expected), tolerance=1e-12)))
cat("R -> Zig native -> R + SLP binary framing: PASS\n")
